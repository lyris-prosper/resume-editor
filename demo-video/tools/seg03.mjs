// 03 对准岗位：粘贴 JD → DeepSeek 拆出要求 → 要求对应经历 → 确认选材和表达 → 选版式 → 生成简历
import fs from 'node:fs'
import { launch, Take, setState, getState, BASE } from './rec.mjs'
const DIR = '../takes/seg03'
const start = JSON.parse(fs.readFileSync('../takes/seg02/state-end.json', 'utf8'))
const exp = start.library.experiences.find((e) => e.org.includes('活动报名'))
const JD = fs.readFileSync('./jd.txt', 'utf8').trim()
const env = await launch()
const { page } = env
await setState(page, start)
await page.goto(`${BASE}/app/library/${exp.id}`)
await page.waitForSelector('text=这段经历里的事')
await page.waitForTimeout(1200)
const t = new Take(env, DIR)
t.pos = { x: 900, y: 420 }
await page.mouse.move(t.pos.x, t.pos.y)
await t.start()
await t.wait(1200)
await t.click('nav[aria-label="工作台"] >> text=岗位', { name: 'click:jobs-tab' })
await page.waitForSelector('textarea[aria-label="招聘信息全文"]')
t.mark('newjob')
await t.wait(1400)
await t.click('textarea[aria-label="招聘信息全文"]', { fx: 0.4, fy: 0.3, name: 'click:jd' })
await t.wait(300)
await t.paste(JD, { name: 'paste:jd' })
await t.wait(2600)
await page.screenshot({ path: `${DIR}/check-jd.png`, scale: 'css' })
await t.click('button:has-text("开始适配")', { name: 'click:parse-job' })
await page.waitForURL(/\/app\/jobs\/job_/, { timeout: 120000 })
t.mark('match')
await page.waitForSelector('text=条有依据', { timeout: 60000 })
t.mark('matched')
await t.moveTo(760, 300, { duration: 800 })
await t.wait(2800)
await page.screenshot({ path: `${DIR}/check-match.png`, scale: 'css' })
// 聚焦一条要求及对应经历
const idx = await page.evaluate(() => [...document.querySelectorAll('li.group\\/r')].findIndex((li) => /P95/.test(li.querySelector('textarea')?.value ?? '')))
console.log('req idx', idx)
const row = page.locator('li.group\\/r').nth(Math.max(idx, 0))
await t.scrollTo(row, 260, { x: 760, y: 450, duration: 1200, name: 'scroll:req' })
await t.rect('req-row', row)
const cand = row.locator('button[aria-pressed]', { hasText: '性能与可靠性' }).first()
const hasCand = await cand.count()
if (hasCand) await t.hover(cand, { fx: 0.35, dwell: 0 })
else await t.hover(row, { fx: 0.3, dwell: 0 })
t.mark('focus:req')
await t.wait(3200)
await page.screenshot({ path: `${DIR}/check-req.png`, scale: 'css' })
fs.writeFileSync(`${DIR}/req-row.txt`, await row.innerText() + '\n' + await row.locator('textarea').inputValue())
// 确认选材：把右侧没勾上的事都勾上
const aside = page.locator('aside').last()
await t.moveTo(1240, 260, { duration: 900 })
t.mark('picks')
await t.wait(1200)
for (let i = 0; i < 10; i++) {
  const off = aside.locator('button[aria-pressed="false"]').first()
  if (!(await off.count())) break
  await t.click(off, { fx: 0.25, dwell: 260, after: 380, name: `click:pick${i}` })
}
await t.wait(1600)
await page.screenshot({ path: `${DIR}/check-picks.png`, scale: 'css' })
// 调整表达：确认这条表达
await t.click('button:has-text("下一步：调整表达")', { name: 'click:adjust' })
await page.waitForSelector('text=不添加事实', { timeout: 10000 })
const adj = page.locator('article', { has: page.locator('h3', { hasText: '性能与可靠性' }) }).first()
await t.wait(1200)
await t.scrollTo(adj, 170, { x: 760, y: 450, duration: 1100, name: 'scroll:adjust' })
await t.rect('adjust-item', adj)
await t.hover(adj.locator('p').first(), { fx: 0.4, dwell: 0 })
t.mark('expression')
await t.wait(2800)
await page.screenshot({ path: `${DIR}/check-adjust.png`, scale: 'css' })
// 选版式
await t.click('button:has-text("下一步：选版式")', { name: 'click:build' })
await page.waitForSelector('text=选一套版式')
await t.wait(1800)
await t.click('button[aria-pressed]:has-text("页眉色带")', { fy: 0.3, name: 'click:tpl-banner' })
await t.wait(1500)
await t.click('button[aria-pressed]:has-text("简洁标准")', { fy: 0.3, name: 'click:tpl-classic' })
await t.wait(1800)
await page.screenshot({ path: `${DIR}/check-build.png`, scale: 'css' })
await t.click('button:has-text("件事生成简历")', { name: 'click:generate' })
await page.waitForURL(/\/app\/resumes\/cv_/)
t.mark('studio')
await t.moveTo(1000, 420, { duration: 900 })
await t.wait(3200)
await page.screenshot({ path: `${DIR}/check-studio.png`, scale: 'css' })
const res = await t.stop()
fs.writeFileSync(`${DIR}/state-end.json`, JSON.stringify(await getState(page)))
fs.writeFileSync(`${DIR}/url-end.txt`, page.url())
console.log('frames', res.frames.length, 'sec', ((res.frames.at(-1).t - res.t0) / 1000).toFixed(1), page.url())
console.log(res.markers.map((m) => `${((m.t - res.t0) / 1000).toFixed(2)} ${m.name}`).join('\n'))
await env.browser.close()
